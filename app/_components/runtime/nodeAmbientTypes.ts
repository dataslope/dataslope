/**
 * Ambient declarations for the Node surface almostnode provides.
 *
 * The language service used to be configured with TypeScript's DOM library,
 * which is wrong twice over for these playgrounds: it offers completions for
 * things that do not exist at runtime (`alert`, `document`, and even
 * `ActiveXObject`), and it says nothing about `process`, `Buffer` or
 * `require`, which do. The JS/TS playgrounds load `lib.es*` plus
 * `lib.webworker` (the worker globals almostnode really has) and these
 * declarations on top.
 *
 * The shimmed modules are declared in shorthand (`declare module "fs";`),
 * which types them as `any`: enough for the checker to accept every import
 * shape without inventing errors about modules it cannot see, and honest
 * about the fact that these are shims rather than the real thing.
 */

