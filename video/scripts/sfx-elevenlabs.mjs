#!/usr/bin/env node
/**
 * Generates the sound effects described in sfx/elevenlabs.json with the
 * ElevenLabs sound-generation API, into public/sfx/el-<name>.wav: trimmed of
 * the silence the model leaves at either end, normalized to a 0 dBFS peak
 * (<Sfx level> sets the mix level), and indexed in sounds.json and
 * accents.json beside the synthesized palette (scripts/sfx.mjs).
 *
 *   npm run sfx:elevenlabs               # generate only the sounds not on disk
 *   npm run sfx:elevenlabs -- --only tap # generate these again (costs credits)
 *   npm run sfx:elevenlabs -- --dry-run  # what it would generate, no API call
 *   npm run sfx:elevenlabs -- --only x --reprocess  # re-trim the kept MP3, free
 *
 * The model is SFX v3 (`eleven_text_to_sound_v3`, released 2026-10-29) unless
 * a sound names another with `model`. v3 follows a prompt that lists several
 * events in order ("a whoosh, then a click, then a bell") far more closely
 * than v2 did, which is what a logo reveal's sound is made of. The API still
 * defaults to v2 when no model is sent, so the model is always sent. The
 * first eight sounds were made on v2 and say so; ElevenLabs removes v2 on
 * 2027-03-01, after which they can only be regenerated by moving them to v3.
 *
 * `reverse: true` plays a sound backwards: a shimmer or a bell that decays
 * becomes one that swells into its last instant, which is how a build-up into
 * the moment a reveal lands is made from a sound the model makes forwards.
 *
 * Generation is billed in credits, so a sound already on disk is never
 * generated again unless --only names it; edit a prompt and the run says the
 * file is stale rather than spending on it. Measured 2026-10-16: 14 credits
 * for a 2.5 s sound on v2. sfx/elevenlabs.lock.json records the prompt and
 * model each file was made from. Needs ELEVENLABS_API_KEY.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { encodeWav, indexSounds, SR } from "./lib/wav.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DEFS = join(ROOT, "sfx", "elevenlabs.json");
/** The model a sound is generated on when its entry names none. */
const DEFAULT_MODEL = "eleven_text_to_sound_v3";
/** Deprecated by ElevenLabs, removed 2027-03-01. */
const RETIRING = { eleven_text_to_sound_v2: "2027-03-01" };
/** 192 kbps, the best MP3 the Creator plan is sent; it is decoded and
 *  re-encoded as WAV here anyway. */
const FORMAT = "mp3_44100_192";
const LOCK = join(ROOT, "sfx", "elevenlabs.lock.json");
const RAW = join(ROOT, ".generated", "sfx");
const OUT = join(ROOT, "public", "sfx");

const args = process.argv.slice(2);
const dry = args.includes("--dry-run");
const only = args.includes("--only") ? args[args.indexOf("--only") + 1].split(",") : null;
const defs = JSON.parse(readFileSync(DEFS, "utf8"));
const lock = existsSync(LOCK) ? JSON.parse(readFileSync(LOCK, "utf8")) : {};
const modelOf = (d) => d?.model ?? DEFAULT_MODEL;
const same = (a, b) =>
  a &&
  b &&
  a.prompt === b.prompt &&
  a.seconds === b.seconds &&
  a.influence === b.influence &&
  modelOf(a) === modelOf(b) &&
  !!a.reverse === !!b.reverse;
// --reprocess re-trims the raw MP3 a sound was generated as (.generated/sfx),
// with no API call: after a change to `reverse` or to the trimming.
const reprocess = args.includes("--reprocess");
if (reprocess && !only) throw new Error("--reprocess re-trims the sounds named with --only");

const todo = Object.keys(defs).filter((name) => (only ? only.includes(name) : !existsSync(join(OUT, `el-${name}.wav`))));
for (const name of Object.keys(defs)) {
  if (!todo.includes(name) && existsSync(join(OUT, `el-${name}.wav`)) && !same(defs[name], lock[name])) {
    console.warn(`  ! el-${name}: its prompt changed since it was generated; --only ${name} to regenerate`);
  }
}
if (!todo.length) {
  console.log("Nothing to generate.");
  process.exit(0);
}
console.log(`${dry ? "Would generate" : reprocess ? "Reprocessing" : "Generating"} ${todo.length}: ${todo.join(", ")} (${todo.reduce((s, n) => s + defs[n].seconds, 0).toFixed(1)} s)`);
for (const name of todo) {
  const model = modelOf(defs[name]);
  console.log(`  el-${name.padEnd(20)} ${model}${RETIRING[model] ? `, which ElevenLabs removes on ${RETIRING[model]}` : ""}`);
}
// The API takes 0.5 to 30 s and answers anything else with a 400, which would
// stop a run part-way through.
const outside = todo.filter((n) => !(defs[n].seconds >= 0.5 && defs[n].seconds <= 30));
if (outside.length) {
  console.error(`seconds must be 0.5 to 30: ${outside.map((n) => `${n} (${defs[n].seconds})`).join(", ")}`);
  process.exit(1);
}
if (dry) process.exit(0);
if (!reprocess && !process.env.ELEVENLABS_API_KEY) throw new Error("ELEVENLABS_API_KEY is not set");

mkdirSync(RAW, { recursive: true });
try {
  for (const name of todo) {
    const { prompt, seconds, influence, reverse } = defs[name];
    const model = modelOf(defs[name]);
    const mp3 = join(RAW, `${name}.mp3`);
    if (reprocess) {
      if (!existsSync(mp3) || !same({ ...defs[name], reverse: false }, { ...lock[name], reverse: false })) {
        throw new Error(`${name}: no raw MP3 of this prompt in .generated/sfx to reprocess`);
      }
    } else {
      const res = await fetch(`https://api.elevenlabs.io/v1/sound-generation?output_format=${FORMAT}`, {
        method: "POST",
        headers: { "xi-api-key": process.env.ELEVENLABS_API_KEY, "Content-Type": "application/json" },
        body: JSON.stringify({ text: prompt, duration_seconds: seconds, prompt_influence: influence, model_id: model }),
      });
      if (!res.ok) throw new Error(`${name}: ${res.status} ${await res.text()}`);
      writeFileSync(mp3, Buffer.from(await res.arrayBuffer()));
    }
    const pair = trim(decode(mp3));
    const { bytes, seconds: kept } = encodeWav(reverse ? pair.map((c) => c.reverse()) : pair);
    writeFileSync(join(OUT, `el-${name}.wav`), bytes);
    lock[name] = { prompt, seconds, influence, model, ...(reverse ? { reverse: true } : {}) };
    console.log(`  ✓ el-${name}  ${kept.toFixed(2)} s (${model})`);
    // Saved after every sound, so an interrupted run keeps what it paid for.
    writeFileSync(LOCK, JSON.stringify(lock, null, 2) + "\n");
  }
} finally {
  // Indexed whatever happened, so a sound written before a failure is listed.
  indexSounds(OUT);
}

/** The MP3 as two float channels at the palette's rate. */
function decode(path) {
  const r = spawnSync("npx", ["remotion", "ffmpeg", "-hide_banner", "-loglevel", "error", "-i", path, "-ac", "2", "-ar", String(SR), "-c:a", "pcm_s16le", "-f", "wav", "pipe:1"], {
    cwd: ROOT,
    maxBuffer: 1 << 28,
    shell: process.platform === "win32",
  });
  if (r.status !== 0) throw new Error(`ffmpeg: ${r.stderr}`);
  const wav = r.stdout;
  let at = 12;
  while (wav.toString("ascii", at, at + 4) !== "data") at += 8 + wav.readUInt32LE(at + 4);
  const pcm = wav.subarray(at + 8);
  const n = pcm.length >> 2;
  const l = new Float64Array(n);
  const rr = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    l[i] = pcm.readInt16LE(i * 4) / 32768;
    rr[i] = pcm.readInt16LE(i * 4 + 2) / 32768;
  }
  return [l, rr];
}

/** Cuts the near-silence the model pads either end with: from 5 ms before the
 *  first sample within 40 dB of the peak to 30 ms after the last within 60 dB. */
function trim([l, r]) {
  const amp = (i) => Math.max(Math.abs(l[i]), Math.abs(r[i]));
  let peak = 0;
  for (let i = 0; i < l.length; i++) peak = Math.max(peak, amp(i));
  let a = 0;
  while (a < l.length && amp(a) < peak * 0.01) a++;
  let b = l.length - 1;
  while (b > a && amp(b) < peak * 0.001) b--;
  a = Math.max(0, a - Math.round(0.005 * SR));
  b = Math.min(l.length, b + Math.round(0.03 * SR));
  return [l.slice(a, b), r.slice(a, b)];
}
