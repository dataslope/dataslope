#!/usr/bin/env node
/**
 * Generate the Mermaid brand-token fallback map from app/brand.css, so the
 * hex fallbacks in app/_components/mdx/mermaid.tsx cannot drift from the
 * ramps. Only concrete hex `--ds-*` declarations are extracted — aliases like
 * `--ds-blue: var(--ds-blue-500)` are skipped because Mermaid runs color math
 * and needs concrete colors. Output: lib/generated/brand-fallbacks.js
 * (gitignored; committed `.d.ts` sibling). Runs from dev, build, postinstall.
 */
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SRC_FILE = join(ROOT, "app", "brand.css");
const OUT_FILE = join(ROOT, "lib", "generated", "brand-fallbacks.js");

const css = readFileSync(SRC_FILE, "utf8");

const tokens = {};
for (const [, name, hex] of css.matchAll(
  /(--ds-[\w-]+)\s*:\s*(#[0-9a-fA-F]{3,8})\s*;/g,
)) {
  tokens[name] = hex;
}

// A brand.css refactor that stops this regex matching must fail the build
// loudly, not ship an empty fallback map.
if (Object.keys(tokens).length === 0) {
  throw new Error(`build-brand-fallbacks: no --ds-* hex tokens found in ${SRC_FILE}`);
}

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(
  OUT_FILE,
  "// Generated by scripts/build-brand-fallbacks.mjs from app/brand.css, do not edit.\n" +
    `export default ${JSON.stringify(tokens, null, 2)};\n`,
);
console.log(
  `build-brand-fallbacks: ${Object.keys(tokens).length} tokens → lib/generated/brand-fallbacks.js`,
);
