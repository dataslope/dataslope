#!/usr/bin/env node
/**
 * Optimize the raster course/interview illustrations and generate their
 * manifest.
 *
 * Why this exists:
 *
 * The Recraft-generated topic images (`assets/course-art/*.png` — transparent
 * PNGs that read on both light `#ffffff` and dark `#121212` backgrounds) must
 * be crushed before they are served, and every lesson that embeds one needs
 * the image's intrinsic width/height so `<Illustration>` can reserve layout
 * space (no CLS) without shipping the raw file.
 *
 * Unlike the repo's other generated-asset scripts (search-index, svg-gallery,
 * brand-fallbacks — cheap text passes that fully regenerate every build), image
 * encoding is expensive, so this script is *incremental and its outputs are
 * committed*:
 *
 *   - For each source PNG it writes an optimized `.png` + `.webp` pair to
 *     `public/course-art/` and records slug → {hash, width, height, formats}
 *     in `lib/generated/course-art.js`.
 *   - Both the optimized assets AND the manifest are committed to git (not
 *     gitignored), so a deploy serves them straight from CDN with zero build
 *     re-encoding.
 *   - A source is only re-encoded when its content hash changes (or its output
 *     files are missing). If nothing changed the script is a true no-op — it
 *     doesn't even rewrite the manifest — so it stays cheap on `dev` / `build`
 *     / `postinstall` and produces no git churn.
 *
 * Bumping `ENCODER_VERSION` invalidates every cached hash, forcing a one-time
 * re-encode after an encoder-settings change.
 *
 * Idempotent. With no source PNGs it writes an empty manifest so typecheck /
 * lint / build stay green before any image has been added.
 */
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SRC_DIR = join(ROOT, "assets", "course-art");
const OUT_DIR = join(ROOT, "public", "course-art");
const MANIFEST_FILE = join(ROOT, "lib", "generated", "course-art.js");

// Cap the longest edge so a hero that displays at ~640px still looks crisp on
// 2x displays without shipping a 2048px original. `withoutEnlargement` keeps
// smaller sources untouched.
const MAX_EDGE = 1600;

// Bump to invalidate every cached hash after changing the encode settings
// below (resize cap, png/webp options). Forces a one-time full re-encode.
const ENCODER_VERSION = "1";

/** Lowercase, hyphenate to a URL/file-safe slug (mirrors the illustration
 *  helper so filenames stay predictable). */
function slugify(value) {
  return value
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/** Read the PNG sources, if any. A missing folder is not an error — it just
 *  means no images have been dropped in yet. */
function listSources() {
  let entries;
  try {
    entries = readdirSync(SRC_DIR);
  } catch {
    return [];
  }
  return entries
    .filter((name) => extname(name).toLowerCase() === ".png")
    .filter((name) => statSync(join(SRC_DIR, name)).isFile())
    .sort();
}

/** Load the previously generated manifest so unchanged images can be skipped.
 *  The file is an ES module (`export default {…}`); rather than `import()` it
 *  (which warns under this package's CommonJS-typed package.json), pull the
 *  JSON literal out of the text — the script writes it, so the shape is known.
 *  Absent/unparseable manifest → treat everything as new. */
function loadPriorManifest() {
  if (!existsSync(MANIFEST_FILE)) return {};
  try {
    const text = readFileSync(MANIFEST_FILE, "utf8");
    const match = text.match(/export default\s*(\{[\s\S]*\})\s*;?\s*$/);
    return match ? JSON.parse(match[1]) : {};
  } catch {
    return {};
  }
}

/** Serialize the manifest to its committed ES-module form. */
function renderManifest(manifest) {
  const sorted = Object.fromEntries(
    Object.keys(manifest)
      .sort()
      .map((k) => [k, manifest[k]]),
  );
  const banner =
    "// GENERATED by scripts/build-course-art.mjs — do not edit by hand.\n" +
    "// Committed; rebuilt (incrementally) from assets/course-art/*.png.\n";
  return `${banner}export default ${JSON.stringify(sorted, null, 2)};\n`;
}

async function main() {
  const sources = listSources();
  const prior = loadPriorManifest();

  mkdirSync(OUT_DIR, { recursive: true });
  mkdirSync(dirname(MANIFEST_FILE), { recursive: true });

  // Load sharp lazily — only needed when an image actually has to be encoded,
  // so the "nothing changed" / "no images yet" paths never touch the binary.
  let sharp = null;
  const ensureSharp = async () => {
    if (sharp) return sharp;
    try {
      ({ default: sharp } = await import("sharp"));
    } catch (err) {
      throw new Error(
        `build-course-art: an image needs (re)encoding but the "sharp" package ` +
          `failed to load — run \`npm install\`. (${err.message})`,
      );
    }
    return sharp;
  };

  const manifest = {};
  const seen = new Map();
  let encoded = 0;
  let cached = 0;

  for (const name of sources) {
    const slug = slugify(name.replace(/\.png$/i, ""));
    if (!slug) {
      console.warn(`build-course-art: skipping "${name}" — empty slug.`);
      continue;
    }
    if (seen.has(slug)) {
      throw new Error(
        `build-course-art: "${name}" and "${seen.get(slug)}" both slugify to ` +
          `"${slug}". Rename one so every image has a unique slug.`,
      );
    }
    seen.set(slug, name);

    const input = readFileSync(join(SRC_DIR, name));
    const hash = createHash("sha256")
      .update(ENCODER_VERSION)
      .update(input)
      .digest("hex");

    const pngOut = join(OUT_DIR, `${slug}.png`);
    const webpOut = join(OUT_DIR, `${slug}.webp`);

    // Skip when the source is unchanged and both outputs are still on disk.
    if (
      prior[slug]?.hash === hash &&
      existsSync(pngOut) &&
      existsSync(webpOut)
    ) {
      manifest[slug] = prior[slug];
      cached += 1;
      continue;
    }

    const s = await ensureSharp();
    // `rotate()` honors any EXIF orientation before we read dimensions.
    const base = s(input, { limitInputPixels: 268402689 }).rotate().resize({
      width: MAX_EDGE,
      height: MAX_EDGE,
      fit: "inside",
      withoutEnlargement: true,
    });

    const pngBuf = await base
      .clone()
      .png({ compressionLevel: 9, effort: 10 })
      .toBuffer({ resolveWithObject: true });
    const webpBuf = await base
      .clone()
      .webp({ quality: 80, alphaQuality: 100, effort: 6 })
      .toBuffer();

    const { width, height } = pngBuf.info;
    writeFileSync(pngOut, pngBuf.data);
    writeFileSync(webpOut, webpBuf);
    manifest[slug] = { hash, width, height, formats: ["webp", "png"] };
    encoded += 1;

    const pngKb = (pngBuf.data.length / 1024).toFixed(0);
    const webpKb = (webpBuf.length / 1024).toFixed(0);
    console.log(
      `build-course-art: encoded ${slug}  ${width}x${height}  ` +
        `png ${pngKb}kB / webp ${webpKb}kB`,
    );
  }

  // Prune optimized files whose source was removed or renamed.
  let pruned = 0;
  for (const file of readdirSync(OUT_DIR)) {
    const ext = extname(file).toLowerCase();
    if (ext !== ".png" && ext !== ".webp") continue;
    const slug = file.slice(0, -ext.length);
    if (!manifest[slug]) {
      rmSync(join(OUT_DIR, file));
      pruned += 1;
    }
  }

  // Rewrite the manifest only when it actually changed — keeps the script a
  // true no-op (and produces no git diff) when nothing was re-encoded.
  const next = renderManifest(manifest);
  const current = existsSync(MANIFEST_FILE)
    ? readFileSync(MANIFEST_FILE, "utf8")
    : null;
  if (next !== current) writeFileSync(MANIFEST_FILE, next);

  console.log(
    `build-course-art: ${encoded} encoded, ${cached} cached, ${pruned} pruned ` +
      `(${Object.keys(manifest).length} image(s) total)`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
