#!/usr/bin/env node
// Generates app/_components/completion/staticLists/phpBuiltins.generated.ts
// from JetBrains' phpstorm-stubs (Apache-2.0): every internal function in
// the extensions php-wasm ships, with its signature and one-line summary,
// so the PHP editors complete `array_` with the whole family instead of a
// hand-picked dozen. Run by hand when the stub list or PHP version moves;
// the output is committed.
//
//   node scripts/build-php-builtins.mjs            # fetch from GitHub
//   node scripts/build-php-builtins.mjs --from DIR # parse local copies
//
// Outbound fetches respect HTTPS_PROXY when NODE_USE_ENV_PROXY=1 is set.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const STUBS_REF = "master";
const STUB_FILES = [
  "Core/Core.php",
  "standard/standard_0.php",
  "standard/standard_1.php",
  "standard/standard_2.php",
  "standard/standard_3.php",
  "standard/standard_4.php",
  "standard/standard_5.php",
  "standard/standard_6.php",
  "standard/standard_7.php",
  "standard/standard_8.php",
  "standard/standard_9.php",
  "pcre/pcre.php",
  "mbstring/mbstring.php",
  "json/json.php",
  "date/date.php",
  "ctype/ctype.php",
];

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(
  here,
  "..",
  "app/_components/completion/staticLists/phpBuiltins.generated.ts",
);

async function loadStub(file, fromDir) {
  if (fromDir) {
    return readFileSync(path.join(fromDir, file.replace("/", "_")), "utf8");
  }
  const url = `https://raw.githubusercontent.com/JetBrains/phpstorm-stubs/${STUBS_REF}/${file}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

/** `#[Attr(...)]` inside a parameter list, and PHPStorm's own type
 *  decorations, are noise in a popup. */
function cleanParams(params) {
  return (
    params
      // A parameter that only exists up to some older PHP version is a
      // second spelling of the one that follows it; keep the current one.
      .replace(/#\[PhpStormStubsElementAvailable\([^)]*\bto:[^)]*\)\]\s*[^,]+,?/g, "")
      .replace(/#\[[^\]]*\]/g, "")
      .replace(/\s+/g, " ")
      .replace(/\( /g, "(")
      .replace(/ ,/g, ",")
      .replace(/,\s*$/, "")
      .trim()
  );
}

function summaryOf(docblock) {
  for (const raw of docblock.split("\n")) {
    const line = raw
      .replace(/^\s*\/?\*+\s?/, "")
      .replace(/<[^>]+>/g, "")
      .trim();
    if (!line || line.startsWith("@")) continue;
    // Version banners (`(PHP 5 >= 5.2.0, PHP 7, PHP 8)`) precede the summary.
    if (/^\(PHP\b/.test(line)) continue;
    return line.replace(/\s+/g, " ").slice(0, 120);
  }
  return "";
}

// The docblock must be the one directly above the function: `(?!\*\/)`
// keeps the lazy match from swallowing an earlier block and the code
// between.
const FUNCTION_RE =
  /\/\*\*((?:(?!\*\/)[\s\S])*?)\*\/\s*((?:#\[[^\n]*\]\s*)*)function\s+(\w+)\s*\(([\s\S]*?)\)\s*(?::\s*([\w?|\\ ]+?))?\s*\{\s*\}/g;

async function main() {
  const fromIdx = process.argv.indexOf("--from");
  const fromDir = fromIdx >= 0 ? process.argv[fromIdx + 1] : null;
  const byName = new Map();
  for (const file of STUB_FILES) {
    const text = await loadStub(file, fromDir);
    for (const m of text.matchAll(FUNCTION_RE)) {
      const [, docblock, attrs, name, params, ret] = m;
      if (/#\[Deprecated/.test(attrs)) continue;
      if (byName.has(name)) continue;
      byName.set(name, [
        name,
        cleanParams(params),
        (ret ?? "").trim(),
        summaryOf(docblock),
      ]);
    }
  }
  const rows = [...byName.values()].sort((a, b) => a[0].localeCompare(b[0]));
  const body = rows.map((r) => `  ${JSON.stringify(r)},`).join("\n");
  const out = `// GENERATED by scripts/build-php-builtins.mjs from JetBrains/phpstorm-stubs
// (Apache-2.0, see THIRD-PARTY-NOTICES.md). Do not edit by hand.
// ${rows.length} internal functions: name, parameter list, return type, summary.

export type PhpBuiltin = readonly [
  name: string,
  params: string,
  returns: string,
  summary: string,
];

export const PHP_BUILTINS: readonly PhpBuiltin[] = [
${body}
];
`;
  writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${rows.length} functions`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
