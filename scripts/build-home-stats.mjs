#!/usr/bin/env node
/**
 * Precompute the home page's corpus figures from `content/`: workerd has no
 * filesystem, so scanning ~800 MDX files at request time 500s whenever `/`
 * renders on demand. The counts stay raw here — `app/page.tsx` floors them
 * for display. Output: lib/generated/home-stats.js (gitignored; committed
 * `.d.ts` sibling). Runs from dev, build, postinstall.
 */
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const CONTENT = join(ROOT, "content");
const OUT_FILE = join(ROOT, "lib", "generated", "home-stats.js");

function readMdxFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...readMdxFiles(full));
    else if (entry.name.endsWith(".mdx")) out.push(readFileSync(full, "utf8"));
  }
  return out;
}

const countMatches = (texts, pattern) =>
  texts.reduce((total, text) => total + (text.match(pattern)?.length ?? 0), 0);

/** Exported so the freshness test can re-derive without duplicating the rules. */
export function readHomeStats() {
  const allMdx = [
    ...readMdxFiles(join(CONTENT, "courses")),
    ...readMdxFiles(join(CONTENT, "fumadocs-dev")),
    ...readMdxFiles(join(CONTENT, "interview")),
  ];

  return {
    // Runnable blocks: executable `<CodeBlock>` (non-SQL) + `<SqlCodeBlock>`.
    runnableCodeBlocks:
      countMatches(allMdx, /<CodeBlock[\s/>]/g) +
      countMatches(allMdx, /<SqlCodeBlock[\s/>]/g),
    // Auto-graded challenges: `<ChallengeCard>` + `<SqlChallengeCard>`.
    codeChallenges:
      countMatches(allMdx, /<ChallengeCard[\s/>]/g) +
      countMatches(allMdx, /<SqlChallengeCard[\s/>]/g),
    // Interview-prep role tracks: top-level dirs under content/interview.
    interviewRoles: readdirSync(join(CONTENT, "interview"), {
      withFileTypes: true,
    }).filter((e) => e.isDirectory()).length,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const stats = readHomeStats();

  // Zero anywhere means the scan stopped matching (renamed component, moved
  // directory); the home page would render "0+ runnable code blocks".
  for (const [key, value] of Object.entries(stats)) {
    if (!value) {
      console.error(
        `build-home-stats: ${key} came out 0. The corpus scan has stopped ` +
          `matching (renamed component, or a moved content directory).`,
      );
      process.exit(1);
    }
  }

  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(
    OUT_FILE,
    "// GENERATED by scripts/build-home-stats.mjs, do not edit by hand.\n" +
      "// Corpus figures for the home page, precomputed so `/` needs no\n" +
      "// filesystem at request time (see the script's header for why).\n" +
      `export default ${JSON.stringify(stats, null, 2)};\n`,
  );
  console.log(
    `build-home-stats: ${stats.runnableCodeBlocks} runnable blocks, ` +
      `${stats.codeChallenges} challenges, ${stats.interviewRoles} roles → ${OUT_FILE}`,
  );
}
