#!/usr/bin/env node
/**
 * Mirror every course's `meta.json` into an ES module the server can import:
 * workerd has no filesystem, so a request-time readdir 500s the moment `/` or
 * `/courses` renders on demand instead of from the incremental cache. Scope
 * is those two pages only; lessons still read MDX at request time (Fumadocs
 * `dynamic` mode). The popularity ranking is deliberately NOT emitted here —
 * it is hand-curated and lives in `lib/courseCatalog.ts`.
 *
 * Output: lib/generated/course-catalog.js (gitignored; committed `.d.ts`
 * sibling). Runs from dev, build, postinstall. Restart `next dev` after
 * adding a course.
 */
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SRC_DIR = join(ROOT, "content", "courses");
const OUT_FILE = join(ROOT, "lib", "generated", "course-catalog.js");

/** Read `content/courses/`, keeping only root courses with a title.
 *  Exported so the freshness test can compare against the emitted module
 *  without duplicating the selection rules. */
export function readCourseCatalog() {
  const courses = [];
  for (const entry of readdirSync(SRC_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    let meta;
    try {
      meta = JSON.parse(
        readFileSync(join(SRC_DIR, entry.name, "meta.json"), "utf8"),
      );
    } catch {
      continue; // No meta.json or unreadable — same as the old readdir loop.
    }
    if (meta.root !== true || typeof meta.title !== "string") continue;
    courses.push({
      slug: entry.name,
      title: meta.title,
      description:
        typeof meta.description === "string" ? meta.description : "",
      tags: meta.tags ?? {},
    });
  }
  // Sort by slug: readdir order is filesystem-defined and would churn the file.
  return courses.sort((a, b) => a.slug.localeCompare(b.slug));
}

// Only run the emit half when invoked as a script, so the test can import
// `readCourseCatalog` without writing to the repo.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const courses = readCourseCatalog();

  // A refactor that stops this finding courses must fail the build, not
  // silently ship an empty catalog (no cards looks like a styling bug).
  if (courses.length === 0) {
    console.error(
      `build-course-catalog: no courses found under ${SRC_DIR}. ` +
        `Expected directories containing a meta.json with "root": true and a title.`,
    );
    process.exit(1);
  }

  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(
    OUT_FILE,
    "// GENERATED by scripts/build-course-catalog.mjs, do not edit by hand.\n" +
      "// Mirrors content/courses/*/meta.json so the catalog needs no filesystem\n" +
      "// at request time (see the script's header for why that matters).\n" +
      `export default ${JSON.stringify(courses, null, 2)};\n`,
  );
  console.log(`build-course-catalog: ${courses.length} courses → ${OUT_FILE}`);
}
